"""MkDocs hook: make repo-relative Markdown links work on the site.

The pages are written as if they lived in TwinRobo-Core's ``docs/`` (where
``docs/cameras.md`` links ``../CONTRIBUTING.md``); the site itself is built from
this repository with Core checked out beside it. On the site those become
site pages; links to anything else in the repo (code, ``LICENSE``, issue
templates) become GitHub URLs. The API reference lives on Read the Docs: links to its
pages (written as ``api/core.md``) go there, and each old ``api/`` address redirects to it.
"""

import json
import posixpath
import re
from pathlib import Path
from urllib.parse import urljoin

REPO = "https://github.com/TwinRobo/TwinRobo-Core"
SITE = "https://twinrobo.github.io/"  # the README links the published site
SITE_PAGES = {"README.md": "index.md", "CONTRIBUTING.md": "contributing.md"}
# site page -> its source in TwinRobo-Core (generated by tools/docs/gen_pages.py)
GENERATED = {
    "contributing.md": "CONTRIBUTING.md",
    "cla.md": "CLA.md",
    "license.md": "COMMERCIAL.md",
}
DOCS = "https://twinrobo-core.readthedocs.io/en/latest/"
API = {  # site page -> its address on Read the Docs
    "api/index.md": "",
    "api/core.md": "cameras/camera/",
    "api/optics.md": "imaging/optics/",
    "api/sensor_isp.md": "imaging/sensor-isp/",
    "api/mujoco.md": "simulators/mujoco/",
    "api/isaac.md": "simulators/isaac/",
    "api/robot_learning.md": "datasets/libero/",
    "api/calibration.md": "tools/calibration/",
    "api/validation.md": "tools/validation/",
}
# old pages split since: a fragment's prefix -> the page that now holds it
SPLIT = {
    "api/core.md": {
        "twinrobo.frame": "cameras/frames/",
        "twinrobo.spec": "cameras/specs/",
        "twinrobo.registry": "cameras/specs/",
        "twinrobo.geometry": "cameras/specs/",
        "twinrobo.stereo": "cameras/stereo/",
        "twinrobo.exceptions": "cameras/errors/",
    },
    "api/robot_learning.md": {"twinrobo.datasets.robocasa": "datasets/robocasa/"},
    "api/mujoco.md": {
        "twinrobo.plugins.mujoco.lidar": "cameras/lidar/",
        "twinrobo.lidar": "cameras/lidar/",
    },
}
REDIRECT = """<!doctype html>
<meta charset="utf-8">
<title>Moved to the TwinRobo API reference</title>
<link rel="canonical" href="{url}">
<noscript><meta http-equiv="refresh" content="0; url={url}"></noscript>
<script>
  const frag = location.hash.slice(1);
  const moved = Object.entries({split}).find(([prefix]) => frag.startsWith(prefix));
  location.replace((moved ? "{docs}" + moved[1] : "{url}") + location.hash);
</script>
<p>This page moved to <a href="{url}">the TwinRobo API reference</a>.</p>
"""


def api_address(page: str, frag: str) -> str:
    """Where an old API page, with its fragment, is on Read the Docs."""
    for prefix, address in SPLIT.get(page, {}).items():
        if frag.startswith(prefix):
            return DOCS + address
    return DOCS + API[page]


LINK = re.compile(r"(\]\()([^)\s]+)(\))")


def _repo_path(src_uri: str) -> str:
    """Where a site page's Markdown lives in the repo."""
    return GENERATED.get(src_uri, f"docs/{src_uri}")


def on_page_markdown(markdown, page, config, files):
    src = page.file.src_uri
    if src in GENERATED:  # edited where its text lives: TwinRobo-Core
        page.edit_url = f"{REPO}/edit/main/{GENERATED[src]}"
    origin = _repo_path(src)
    here = posixpath.dirname(src)

    def fix(m):
        target = m.group(2)
        if target.startswith(SITE):  # a link to this site: keep it on the site being viewed
            page_path, _, frag = target[len(SITE) :].partition("#")
            stem = page_path.rstrip("/")
            dest = "index.md"
            if stem:  # "catalog/" -> catalog.md, "api/" -> api/index.md
                dest = (
                    f"{stem}.md" if files.get_file_from_path(f"{stem}.md") else f"{stem}/index.md"
                )
            for page in (f"{stem}.md", f"{stem}/index.md"):
                if page in API:
                    address = api_address(page, frag)
                    return f"{m.group(1)}{address}{'#' + frag if frag else ''}{m.group(3)}"
            rel = posixpath.relpath(dest, here or ".")
            return f"{m.group(1)}{rel}{'#' + frag if frag else ''}{m.group(3)}"
        if re.match(r"^[a-z]+:", target) or target.startswith("#"):
            return m.group(0)
        path, _, frag = target.partition("#")
        page_path = posixpath.normpath(posixpath.join(here, path))
        if page_path in API:
            address = api_address(page_path, frag)
            return f"{m.group(1)}{address}{'#' + frag if frag else ''}{m.group(3)}"
        url = urljoin(f"{REPO}/blob/main/{origin}", path)
        prefix = f"{REPO}/blob/main/"
        if url.startswith(prefix):
            repo_file = url[len(prefix) :]
            site = SITE_PAGES.get(repo_file)
            if site is None and repo_file.startswith("docs/"):
                site = repo_file[len("docs/") :]
            if site is not None:
                rel = posixpath.relpath(site, here or ".")
                return f"{m.group(1)}{rel}{'#' + frag if frag else ''}{m.group(3)}"
        if not path:
            return m.group(0)
        return f"{m.group(1)}{url}{'#' + frag if frag else ''}{m.group(3)}"

    return LINK.sub(fix, markdown)


def on_post_build(config):
    for page, address in API.items():
        old = page.removesuffix(".md").removesuffix("index").rstrip("/")
        out = Path(config.site_dir) / old / "index.html"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(
            REDIRECT.format(url=DOCS + address, docs=DOCS, split=json.dumps(SPLIT.get(page, {})))
        )
